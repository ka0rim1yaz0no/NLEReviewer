import judgmentData from './judgment-data.mjs';
import {installQuestionBank,validateQuestions,subjects} from './bank.ts';
import {isSituational} from './collections.ts';
import {questions as previousQuestions,clinicalCases} from './previous-authoring-bank.ts';
import {applyClinicalAudit} from './clinical-audit.ts';
import {applyChoiceReview} from './choice-review.ts';
import {applyBankReview} from './bank-review.ts';
import {applyClinicalDifficultyReview} from './clinical-difficulty-review.ts';
import {applicationReviews} from './application-review-data.ts';
import {reviewReferenceDifficulty} from './difficulty-review.mjs';
import {reviewRemainingQuestions} from './decision-review.mjs';
import {correctQuestionFeedback} from './choice-feedback-review.mjs';
import {applyClinicalReferenceCorrections} from './clinical-reference-corrections.mjs';
import {applyChoiceContext} from './choice-context-review.mjs';
import {reviewPriorityCases} from './priority-case-review.mjs';
import {continueClinicalCaseReview} from './clinical-case-continuation.mjs';
import {newStudyQuestions} from './authored-update.mjs';
import type {Question} from './types.ts';

export {originalQuestions,supplementalQuestions,conceptQuestions,situationalQuestions,challengeQuestions,clinicalCases,subjects,shuffled,validateQuestions} from './previous-authoring-bank.ts';
export {previousQuestions};

const edits=validateQuestions(judgmentData);
const editedById=new Map(edits.map(q=>[q.id,q]));
const priorSituationalIds=new Set(previousQuestions.filter(isSituational).map(q=>q.id));
if(edits.some(q=>!priorSituationalIds.has(q.id))){
 throw new Error('A revised question has no active situational record.');
}
export const judgmentQuestions:Question[]=previousQuestions.map(q=>editedById.get(q.id)||q);
export const clinicalAuditQuestions=applyClinicalAudit(judgmentQuestions);
export const choiceReviewedQuestions=applyChoiceReview(clinicalAuditQuestions);
export const fullBankReviewedQuestions=applyBankReview(choiceReviewedQuestions);
const clinicalDifficultyQuestions=applyClinicalDifficultyReview(fullBankReviewedQuestions);
const applicationQuestions=applyBankReview(clinicalDifficultyQuestions,applicationReviews,5);
const referenceReview=reviewReferenceDifficulty(applicationQuestions);
export const referenceDifficultyCounts=referenceReview.counts;
export const applicationReviewedQuestions=validateQuestions(referenceReview.questions);
const decisionReview=reviewRemainingQuestions(applicationReviewedQuestions);
const additionsReview=reviewRemainingQuestions(newStudyQuestions,[...applicationReviewedQuestions,...newStudyQuestions],decisionReview.questions);
export const decisionReviewCounts=decisionReview.counts;
export const decisionQuestions=validateQuestions(decisionReview.questions);
export const decisionStudyQuestions=additionsReview.questions.length?validateQuestions(additionsReview.questions):[];
const sources=[...applicationReviewedQuestions,...newStudyQuestions];
const coreFeedback=correctQuestionFeedback(decisionQuestions,sources);
const additionFeedback=correctQuestionFeedback(decisionStudyQuestions,sources);
export const rationaleQuestions=coreFeedback.questions;
export const rationaleStudyQuestions=additionFeedback.questions;
const originalById=new Map(sources.map(question=>[question.id,question]));
const reviewChoices=(question:Question)=>applyChoiceContext(applyClinicalReferenceCorrections(question),originalById);
export const contextReviewedQuestions=validateQuestions(rationaleQuestions.map(reviewChoices));
export const contextReviewedAdditions=rationaleStudyQuestions.length?validateQuestions(rationaleStudyQuestions.map(reviewChoices)):[];
export const priorityReviewedQuestions=validateQuestions(contextReviewedQuestions.map(question=>reviewPriorityCases(question,originalById)));
export const priorityReviewedAdditions=contextReviewedAdditions.length?validateQuestions(contextReviewedAdditions.map(question=>reviewPriorityCases(question,originalById))):[];
const finishClinicalReview=(question:Question)=>continueClinicalCaseReview(question,originalById);
export const questions=validateQuestions(priorityReviewedQuestions.map(finishClinicalReview));
export const revisedStudyQuestions=priorityReviewedAdditions.length?validateQuestions(priorityReviewedAdditions.map(finishClinicalReview)):[];
export const feedbackReviewCounts={core:coreFeedback.counts,additions:additionFeedback.counts};
export const activeQuestions=questions.filter(q=>!q.retired);
export const revisedSituationalCount=activeQuestions.filter(isSituational).length;
export const questionMap=new Map(questions.map(q=>[q.id,q]));
export const topics=subjects.flatMap(subject=>[...new Set(activeQuestions.filter(q=>q.subject===subject.id).map(q=>q.topic))].map(name=>({id:subject.id+':'+name,name,subject:subject.id,count:activeQuestions.filter(q=>q.subject===subject.id&&q.topic===name).length})));

installQuestionBank(questions,clinicalCases);
